function startHeartbeat() {
  stopHeartbeat();
  lastPongAt = performance.now();
  heartbeatTimer = setInterval(() => {
    if (!channel || channel.readyState !== 'open') return;
    const now = performance.now();
    const id = ++pingCounter;
    pendingPings.set(id, now);
    while (pendingPings.size > 8) pendingPings.delete(pendingPings.keys().next().value);
    try { channel.send(JSON.stringify({ kind: 'ping', id })); } catch { /* Connection state handler reports failures. */ }
    if (now - lastPongAt > 9000) {
      status('#mesh-health', 'DEGRADED');
      $('#mesh-health').classList.remove('good');
      status('#mesh-status', 'Peer heartbeat is late. DataChannel may be stalled; retry Wi-Fi or re-pair if this persists.');
    }
  }, 2500);
}
function stopHeartbeat() {
  if (heartbeatTimer) clearInterval(heartbeatTimer);
  heartbeatTimer = null;
  pendingPings.clear();
}
function recordPong(id) {
  const sentAt = pendingPings.get(id);
  if (sentAt === undefined) return;
  pendingPings.delete(id);
  const rtt = performance.now() - sentAt;
  lastPongAt = performance.now();
  rttSamples.push(rtt);
  if (rttSamples.length > 30) rttSamples.shift();
  status('#mesh-health', rtt < 120 ? 'EXCELLENT' : rtt < 350 ? 'HEALTHY' : 'HIGH LATENCY');
  $('#mesh-health').classList.toggle('good', rtt < 350);
  updateMeshMetrics();
}

