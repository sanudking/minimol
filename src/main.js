function bytesToBase64Url(bytes) {
  let binary = '';
  for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/g, '');
}
function base64UrlToBytes(value) {
  const base64 = value.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - value.length % 4) % 4);
  const binary = atob(base64);
  return Uint8Array.from(binary, char => char.charCodeAt(0));
}
async function encodeSignal(description) {
  const raw = new TextEncoder().encode(JSON.stringify(description));
  if ('CompressionStream' in window) {
    try {
      const stream = new Blob([raw]).stream().pipeThrough(new CompressionStream('gzip'));
      const compressed = new Uint8Array(await new Response(stream).arrayBuffer());
      return `M1G.${bytesToBase64Url(compressed)}`;
    } catch { /* Fall back to uncompressed SDP for older browser implementations. */ }
  }
  return `M1J.${bytesToBase64Url(raw)}`;
}
async function decodeSignal(payload) {
  const [format, encoded] = payload.split('.', 2);
  if (!encoded || !['M1G', 'M1J'].includes(format)) throw new Error('Unrecognized MiniMoL QR code.');
  let bytes = base64UrlToBytes(encoded);
  if (format === 'M1G') {
    if (!('DecompressionStream' in window)) throw new Error('This browser cannot decompress the pairing QR. Update Safari/Chrome or use a newer browser.');
    const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
    bytes = new Uint8Array(await new Response(stream).arrayBuffer());
  }
  if (bytes.length > 48_000) throw new Error('Pairing payload is too large. Generate a fresh offer QR.');
  return JSON.parse(new TextDecoder().decode(bytes));
}
