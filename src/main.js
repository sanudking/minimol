function waitIce(pcRef, timeoutMs = 12_000) {
  if (pcRef.iceGatheringState === 'complete') return Promise.resolve(true);
  return new Promise(resolve => {
    let settled = false;
    let timeout;
    const finish = complete => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      pcRef.removeEventListener('icegatheringstatechange', check);
      resolve(complete);
    };
    const check = () => {
      if (pcRef.iceGatheringState === 'complete') finish(true);
    };
    pcRef.addEventListener('icegatheringstatechange', check);
    timeout = setTimeout(() => finish(false), timeoutMs);
    // Re-check after registering to avoid missing a fast state transition.
    check();
  });
}
