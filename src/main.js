function adaptiveChunkSize() {
  const queued = channel?.bufferedAmount || 0;
  if (queued > 512 * 1024) return 4 * 1024;
  if (queued > 128 * 1024) return 8 * 1024;
  return MAX_CHUNK;
}
async function waitForChannelDrain() {
  if (!channel || channel.readyState !== 'open') throw new Error('DataChannel is not open.');
  if (channel.bufferedAmount <= BUFFER_HIGH_WATER) return;
  await new Promise((resolve, reject) => {
    let settled = false;
    const finish = error => {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      channel?.removeEventListener('bufferedamountlow', check);
      error ? reject(error) : resolve();
    };
    const check = () => { if (!channel || channel.readyState !== 'open') finish(new Error('Peer disconnected while waiting for the send queue.')); else if (channel.bufferedAmount <= BUFFER_LOW_WATER) finish(); };
    const timeout = setTimeout(() => finish(new Error('Peer link is congested; send queue did not drain.')), 30_000);
    channel.addEventListener('bufferedamountlow', check);
    check();
  });
}
async function sendPayload(type, id, seqLen, bytes) {
  if (!channel || channel.readyState !== 'open') throw new Error('DataChannel is not open.');
  for (let offset = 0; offset < bytes.length;) {
    await waitForChannelDrain();
    const chunkLength = Math.min(adaptiveChunkSize(), bytes.length - offset);
    const chunk = bytes.subarray(offset, offset + chunkLength);
    const frame = new ArrayBuffer(15 + chunk.length), view = new DataView(frame);
    view.setUint8(0, type); view.setUint32(1, id, true); view.setUint16(5, seqLen, true); view.setUint32(7, bytes.length, true); view.setUint32(11, offset, true);
    new Uint8Array(frame, 15).set(chunk);
    channel.send(frame);
    activationBytesSent += frame.byteLength;
    offset += chunk.length;
    updateMeshMetrics();
  }
}
function requestNextToken(type, activation, seqLen) {
  const id = ++requestCounter;
  const response = new Promise((resolve, reject) => {
    const timer = setTimeout(() => { if (waitingToken?.id === id) waitingToken = null; reject(new Error('Phone 2 did not return a token before timeout.')); }, REQUEST_TIMEOUT_MS);
    waitingToken = { id, resolve: token => { clearTimeout(timer); resolve(token); }, reject: error => { clearTimeout(timer); reject(error); } };
  });
  sendPayload(type, id, seqLen, new Uint8Array(activation)).catch(error => {
    if (waitingToken?.id === id) { waitingToken.reject(error); waitingToken = null; }
  });
  return response;
}
async function handleMessage(data) {
  if (typeof data === 'string') {
    const message = JSON.parse(data);
    if (message.kind === 'ping') {
      if (channel?.readyState === 'open') channel.send(JSON.stringify({ kind: 'pong', id: message.id }));
    } else if (message.kind === 'pong') {
      recordPong(Number(message.id));
    } else if (message.kind === 'stage-update') {
      setStage(message.stage, message.detail || 'Remote device is processing.');
    } else if (message.kind === 'work-update') {
      phone1Positions = Number(message.phone1) || phone1Positions;
      phone2Positions = Number(message.phone2) || phone2Positions;
      updateMeshMetrics();
    } else if (message.kind === 'hello') {
      if (message.protocol !== APP_PROTOCOL) throw new Error('Phone apps use different protocol versions. Deploy the same release to both.');
      if (message.role === role) throw new Error('Both devices selected the same role. One must be Phone 1 and the other Phone 2.');
      if (message.modelId !== modelId) throw new Error('The two phones loaded different model partitions/releases.');
      remoteHello = true;
      if (channel?.readyState === 'open') { setConnected(true); status('#mesh-health', 'HEALTHY'); $('#mesh-health').classList.add('good'); }
    } else if (message.kind === 'reset' && role === 'phone2') {
      await workerCall('reset');
    } else if (role === 'phone2' && message.kind === 'generation-start') {
      remoteGenerated = 0;
      resetMeshMetrics();
      remoteGenerationLimit = Number(message.maxBytes) || 0;
      p2Ms = 0;
      status('#metric-p2', 'Running…');
      status('#metric-p1', 'Remote');
      status('#metric-link', 'Direct');
      status('#token-count', `0 / ${remoteGenerationLimit} BYTES`);
      $('#output').textContent = 'Phone 2 is processing the prompt and returning byte predictions to Phone 1…';
      setRunState('RUNNING', true);
      setStage('prompt', 'Phone 1 started a new inference request.');
    } else if (role === 'phone2' && message.kind === 'generation-progress') {
      remoteGenerated = Number(message.generated) || remoteGenerated;
      status('#token-count', `${remoteGenerated} / ${remoteGenerationLimit} BYTES RETURNED`);
      $('#output').textContent = `Remote inference active · returned ${remoteGenerated} of ${remoteGenerationLimit} byte predictions.`;
    } else if (role === 'phone2' && message.kind === 'generation-complete') {
      setRunState('COMPLETE', true);
      status('#metric-p2', `${p2Ms.toFixed(0)} ms CPU`);
      $('#output').textContent = `Completed. Phone 2 computed ${remoteGenerated} byte predictions and returned them to Phone 1.`;
      status('#token-count', `${remoteGenerated} BYTES COMPUTED`);
      status('#metric-link', `${Number(message.decodeTps || 0).toFixed(1)} tok/s decode · ${Number(message.totalTps || 0).toFixed(1)} end-to-end`);
    } else if (role === 'phone2' && message.kind === 'generation-error') {
      setRunState('ERROR');
      $('#output').textContent = `Remote generation failed: ${message.error || 'unknown error'}`;
    }
    return;
  }
  if (!(data instanceof ArrayBuffer) || data.byteLength < 15) return;
  activationBytesReceived += data.byteLength;
  updateMeshMetrics();
  const view = new DataView(data), type = view.getUint8(0), id = view.getUint32(1, true);
  const seqLen = view.getUint16(5, true), total = view.getUint32(7, true), offset = view.getUint32(11, true);
  const chunk = new Uint8Array(data, 15);
  if (total > MAX_FRAME_BYTES || offset + chunk.length > total) throw new Error('Invalid activation frame bounds.');
  const key = `${type}:${id}`;
  let item = assemblies.get(key);
  if (!item) { item = { bytes: new Uint8Array(total), received: 0, offsets: new Set(), seqLen }; assemblies.set(key, item); }
  if (item.offsets.has(offset)) return;
  item.offsets.add(offset); item.bytes.set(chunk, offset); item.received += chunk.length;
  if (item.received !== total) return;
  assemblies.delete(key);
  if (role === 'phone2' && (type === 1 || type === 3)) {
    try {
      setStage('phone2', 'Phone 2 is computing Transformer layers 3–5 and the output head.');
      const start = performance.now();
      const response = type === 1
        ? await workerCall('prefill2', { activation: item.bytes.buffer }, [item.bytes.buffer])
        : await workerCall('step2', { activation: item.bytes.buffer }, [item.bytes.buffer]);
      p2Ms += performance.now() - start;
      phone2Positions += type === 1 ? seqLen : 1;
      updateMeshMetrics();
      if (channel?.readyState === 'open') channel.send(JSON.stringify({ kind: 'work-update', phone1: phone1Positions, phone2: phone2Positions }));
      remoteGenerated++;
      setStage('return', 'Phone 2 completed its partition and returned the greedy byte ID.');
      if (channel?.readyState === 'open') channel.send(JSON.stringify({ kind: 'stage-update', stage: 'return', detail: 'Phone 2 completed layers 3–5 + output head.' }));
      const reply = new ArrayBuffer(5);
      const replyView = new DataView(reply);
      replyView.setUint8(0, response.token);
      replyView.setFloat32(1, p2Ms, true);
      await sendPayload(2, id, 1, new Uint8Array(reply));
      if (remoteGenerated % 4 === 0) status('#metric-p2', `${p2Ms.toFixed(0)} ms CPU`);
    } catch (error) {
      const errorBytes = new TextEncoder().encode(error?.message || String(error));
      await sendPayload(6, id, 0, errorBytes);
      setRunState('ERROR');
      $('#output').textContent = `Inference error: ${error?.message || String(error)}`;
      throw error;
    }
  } else if (role === 'phone1' && type === 2) {
    if (item.bytes.length !== 5) throw new Error('Invalid Phone 2 response: expected byte ID and CPU timing.');
    const replyView = new DataView(item.bytes.buffer, item.bytes.byteOffset, item.bytes.byteLength);
    if (waitingToken?.id === id) {
      p2Ms = replyView.getFloat32(1, true);
      setStage('return', 'Next byte ID returned directly from Phone 2.');
      if (generation.length % 4 === 0) status('#metric-p2', `${p2Ms.toFixed(0)} ms CPU`);
      const pending = waitingToken; waitingToken = null; pending.resolve(item.bytes[0]);
    }
  } else if (role === 'phone1' && type === 6) {
    const message = new TextDecoder().decode(item.bytes) || 'Phone 2 inference failed.';
    if (waitingToken?.id === id) { const pending = waitingToken; waitingToken = null; pending.reject(new Error(message)); }
  }
}

function formatByteStream(bytes) {
  const data = new Uint8Array(bytes);
  const decoder = new TextDecoder('utf-8', { fatal: true });
  let output = '';
  for (let i = 0; i < data.length;) {
    const first = data[i];
    if (first >= 0x20 && first <= 0x7e) { output += String.fromCharCode(first); i++; continue; }
    if (first === 0x09 || first === 0x0a || first === 0x0d) { output += String.fromCharCode(first); i++; continue; }
    let length = first >= 0xc2 && first <= 0xdf ? 2 : first >= 0xe0 && first <= 0xef ? 3 : first >= 0xf0 && first <= 0xf4 ? 4 : 0;
    if (length && i + length <= data.length) {
      try { output += decoder.decode(data.subarray(i, i + length)); i += length; continue; }
      catch { /* Render invalid UTF-8 bytes explicitly below. */ }
    }
    output += `\\x${first.toString(16).padStart(2, '0').toUpperCase()}`;
    i++;
  }
  return output || ' ';
}
function appendByte(token, bytes, render = true) {
  bytes.push(token);
  if (render) {
    $('#output').textContent = formatByteStream(bytes);
    status('#token-count', `${bytes.length} BYTES`);
  }
}
async function runGeneration(promptText, maxNew) {
  if (running || role !== 'phone1' || !worker || !connected) throw new Error('Connect both phones and load the Phone 1 partition first.');
  const prompt = new TextEncoder().encode(promptText);
  if (!prompt.length) throw new Error('Enter a non-empty prompt.');
  const tokens = prompt.length > 512 ? prompt.slice(-512) : prompt;
  running = true; generation = []; startedAt = performance.now(); p1Ms = 0; p2Ms = 0;
  resetMeshMetrics();
  $('#output').textContent = ''; status('#metric-p1', 'Running…'); status('#metric-p2', 'Waiting…'); status('#metric-link', 'Measuring…'); setRunState('RUNNING', true); updateGenerate();
  try {
    channel.send(JSON.stringify({ kind: 'generation-start', maxBytes: maxNew }));
    await workerCall('reset');
    channel.send(JSON.stringify({ kind: 'reset' }));
    setStage('prompt', `Prompt encoded into ${tokens.length} UTF-8 byte IDs.`);
    const start = performance.now();
    const first = await workerCall('prefill1', { tokens });
    p1Ms += performance.now() - start;
    phone1Positions += tokens.length;
    updateMeshMetrics();
    channel.send(JSON.stringify({ kind: 'work-update', phone1: phone1Positions, phone2: phone2Positions }));
    setStage('phone1', `Phone 1 processed ${tokens.length} prompt positions through embeddings + layers 0–2.`);
    channel.send(JSON.stringify({ kind: 'stage-update', stage: 'phone1', detail: 'Phone 1 processed the prompt through embeddings + layers 0–2.' }));
    status('#metric-p1', `${p1Ms.toFixed(0)} ms`);
    setStage('link', 'Sending FP32 hidden activations over the direct DataChannel.');
    let next = await requestNextToken(1, first.activation, first.seqLen);
    const decodeStartedAt = performance.now();
    for (let i = 0; i < maxNew; i++) {
      appendByte(next, generation, false);
      if (generation.length === 1 || generation.length % 4 === 0) {
        $('#output').textContent = formatByteStream(generation);
        status('#token-count', `${generation.length} BYTES`);
        channel.send(JSON.stringify({ kind: 'generation-progress', generated: generation.length }));
      }
      if (tokens.length + generation.length >= 512 || i === maxNew - 1) break;
      const t0 = performance.now();
      const activation = await workerCall('step1', { token: next, position: tokens.length + generation.length - 1 });
      p1Ms += performance.now() - t0;
      phone1Positions++;
      updateMeshMetrics();
      channel.send(JSON.stringify({ kind: 'work-update', phone1: phone1Positions, phone2: phone2Positions }));
      if ((generation.length + 1) % 4 === 0) status('#metric-p1', `${p1Ms.toFixed(0)} ms CPU`);
      setStage('phone1', `Phone 1 computed the next hidden state for generated position ${generation.length + 1}.`);
      channel.send(JSON.stringify({ kind: 'stage-update', stage: 'phone1', detail: `Phone 1 completed its three-layer partition for position ${generation.length + 1}.` }));
      setStage('link', 'Transferring the next hidden activation to Phone 2.');
      next = await requestNextToken(3, activation.activation, 1);
    }
    const elapsedMs = performance.now() - startedAt;
    const decodeMs = Math.max(1, performance.now() - decodeStartedAt);
    const decodeTps = generation.length > 1 ? (generation.length - 1) / (decodeMs / 1000) : 0;
    const totalTps = generation.length / (elapsedMs / 1000);
    $('#output').textContent = formatByteStream(generation);
    status('#token-count', `${generation.length} BYTES`);
    status('#metric-p1', `${p1Ms.toFixed(0)} ms CPU`);
    status('#metric-p2', `${p2Ms.toFixed(0)} ms CPU`);
    status('#metric-link', `${decodeTps.toFixed(1)} tok/s`);
    channel.send(JSON.stringify({ kind: 'generation-progress', generated: generation.length }));
    channel.send(JSON.stringify({ kind: 'generation-complete', generated: generation.length, elapsedMs, decodeTps, totalTps }));
    setStage('return', `Completed ${generation.length} generated bytes across both devices.`);
    setRunState('COMPLETE', true);
    return { bytes: [...generation], decodeTps, totalTps, elapsedMs, phone1Ms: p1Ms, phone2Ms: p2Ms };
  } catch (error) {
    setRunState('ERROR'); status('#peer-status', error.message);
    if (channel?.readyState === 'open') channel.send(JSON.stringify({ kind: 'generation-error', error: error.message }));
    if (waitingToken) { waitingToken.reject(error); waitingToken = null; }
    throw error;
  } finally { running = false; updateGenerate(); }
}

