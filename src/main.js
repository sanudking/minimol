function workerCall(type, payload = {}, transfer = []) {
  return new Promise((resolve, reject) => {
    if (!worker) return reject(new Error('Load this phone\'s model partition first.'));
    const id = ++workerCounter;
    const timer = setTimeout(() => { workerPending.delete(id); reject(new Error(`Worker ${type} timed out.`)); }, REQUEST_TIMEOUT_MS);
    workerPending.set(id, { resolve: value => { clearTimeout(timer); resolve(value); }, reject: error => { clearTimeout(timer); reject(error); } });
    worker.postMessage({ id, type, ...payload }, transfer);
  });
}

function openDb() {
  return new Promise((resolve, reject) => {
    const request = indexedDB.open('minimol-local-v1', 1);
    request.onupgradeneeded = () => request.result.createObjectStore('partitions');
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}
async function readPartition(key) {
  const db = await openDb();
  return new Promise((resolve, reject) => {
    const request = db.transaction('partitions', 'readonly').objectStore('partitions').get(key);
    request.onsuccess = () => { db.close(); resolve(request.result || null); };
    request.onerror = () => { db.close(); reject(request.error); };
  });
}
async function savePartition(key, buffer) {
  const db = await openDb();
  return new Promise((resolve, reject) => {
    const tx = db.transaction('partitions', 'readwrite');
    tx.objectStore('partitions').put(buffer, key);
    tx.oncomplete = () => { db.close(); resolve(); };
    tx.onerror = () => { db.close(); reject(tx.error); };
    tx.onabort = () => { db.close(); reject(tx.error || new Error('Local storage transaction aborted.')); };
  });
}
async function sha256(buffer) {
  const digest = await crypto.subtle.digest('SHA-256', buffer);
  return [...new Uint8Array(digest)].map(x => x.toString(16).padStart(2, '0')).join('');
}

