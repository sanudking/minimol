$('#run-integrity').addEventListener('click', async () => {
  const button = $('#run-integrity');
  button.disabled = true;
  status('#challenge-status', 'Running the known-answer challenge across both phones…');
  try {
    const response = await fetch('./models/reference_outputs.json', { cache: 'no-cache' });
    if (!response.ok) throw new Error('Reference fixture is missing from the deployed app. Rebuild and redeploy.');
    const fixture = await response.json();
    const result = await runGeneration(fixture.prompt_utf8, fixture.generated_byte_ids.length);
    const mismatches = [];
    for (let i = 0; i < fixture.generated_byte_ids.length; i++) if (result.bytes[i] !== fixture.generated_byte_ids[i]) mismatches.push(i);
    if (result.bytes.length === fixture.generated_byte_ids.length && mismatches.length === 0) {
      status('#challenge-status', `PASS · ${result.bytes.length}/${fixture.generated_byte_ids.length} byte IDs match the reference exactly. Both phone partitions participated.`);
    } else {
      status('#challenge-status', `MISMATCH · ${mismatches.length} differing positions; first mismatch: ${mismatches[0] ?? 'length'}. Check both phones use the same model release.`);
    }
  } catch (error) { status('#challenge-status', `Challenge failed: ${error.message}`); }
  finally { button.disabled = !(role === 'phone1' && connected && worker); }
});

$('#run-benchmark').addEventListener('click', async () => {
  if (benchmarkRunning || running) return;
  benchmarkRunning = true;
  $('#run-benchmark').disabled = true;
  $('#run-integrity').disabled = true;
  const results = [];
  status('#challenge-status', 'Benchmark: running 3 identical 32-byte trials. Keep both phones awake and on the same Wi-Fi.');
  try {
    for (let trial = 1; trial <= 3; trial++) {
      status('#challenge-status', `Benchmark trial ${trial}/3…`);
      const result = await runGeneration('MiniMoL distributed benchmark', 32);
      results.push(result);
    }
    const decode = results.map(item => item.decodeTps);
    const total = results.map(item => item.totalTps);
    const medianDecode = percentile(decode, 0.5);
    const bestDecode = Math.max(...decode);
    const worstDecode = Math.min(...decode);
    const medianTotal = percentile(total, 0.5);
    status('#challenge-status', `3-trial benchmark complete · median decode ${medianDecode.toFixed(2)} tok/s · range ${worstDecode.toFixed(2)}–${bestDecode.toFixed(2)} tok/s · median end-to-end ${medianTotal.toFixed(2)} tok/s. Repeat under identical network/device conditions to compare builds.`);
  } catch (error) { status('#challenge-status', `Benchmark stopped: ${error.message}`); }
  finally { benchmarkRunning = false; updateGenerate(); }
});

